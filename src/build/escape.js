/* ============================================================
   Экранирование и типографские мелочи для генераторов разметки.

   Раньше эти две функции были дословно скопированы в render.js и
   render-scandere.js. Список единиц в nbsp приходилось бы править
   в двух местах, а расхождение в esc — это уже дыра, а не неудобство.
   ============================================================ */

export const esc = s => String(s)
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;')

/* Неразрывный пробел перед единицей: «297 EP» не должно
   переноситься по строке. */
export const nbsp = s => String(s).replace(/(\d)\s(EP|₽|недел|нед\.|RPS)/g, '$1\u00a0$2')
